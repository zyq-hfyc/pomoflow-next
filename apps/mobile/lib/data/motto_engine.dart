Motto randomBuiltinMotto() =>
    kBuiltinMottos[Random().nextInt(kBuiltinMottos.length)];

/// 轮播进度持有者。保持无状态可测:调用方传当前自定义池,
/// 引擎内部记住「已播过的下标」。
class MottoPicker {
  final Set<int> _playedCustom = {};

  /// 初始条目:有自定义 → 第一条并标记已播;无 → 随机内置。
  Motto initial(List<Motto> custom) {
    if (custom.isEmpty) return randomBuiltinMotto();
    _playedCustom
      ..clear()
      ..add(0);
    return _normalize(custom[0]);
  }

  /// 下一条:自定义池取「首个未播过的」;全部播过则重置进度再来一轮;
  /// 空池 → 随机内置。
  Motto next(List<Motto> custom) {
    if (custom.isEmpty) return randomBuiltinMotto();
    var unplayed = [
      for (var i = 0; i < custom.length; i++)
        if (!_playedCustom.contains(i)) i,
    ];
    if (unplayed.isEmpty) {
      _playedCustom.clear();
      unplayed = List.generate(custom.length, (i) => i);
    }
    final i = unplayed.first;
    _playedCustom.add(i);
    return _normalize(custom[i]);
  }

  Motto _normalize(Motto m) {
    final author = m.$2.trim();
    return (m.$1, author.isEmpty ? kMottoDefaultAuthor : author);
  }
}
